def compile_words(source: pathlib.Path) -> list:
    with tempfile.TemporaryDirectory() as scratch:
        binary = pathlib.Path(scratch) / "shader.spv"
        subprocess.run(
            ["glslangValidator", "-V", "--target-env", "vulkan1.1", f"-I{FSR}", f"-I{SHADERS}", str(source), "-o", str(binary)],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        data = binary.read_bytes()
    return list(struct.unpack(f"<{len(data) // 4}I", data))


def main() -> int:
    text = [HEADER]
    for file_name, symbol in PROGRAMS:
        words = compile_words(SHADERS / file_name)
        text.append(f"\nconstexpr uint32_t {symbol}[] = {{\n")
        for i in range(0, len(words), 6):
            text.append("\t" + " ".join(f"0x{w:08x}u," for w in words[i : i + 6]) + "\n")
        text.append("};\n")
    OUTPUT.write_text("".join(text))
    return 0


if __name__ == "__main__":
    sys.exit(main())
