#ifndef KYTY_AGENT_INCLUDE_KYTY_AGENT_RUNNER_SCENECHECKPOINT_H_
#define KYTY_AGENT_INCLUDE_KYTY_AGENT_RUNNER_SCENECHECKPOINT_H_

#include "Kyty/Agent/Runner/CaptureMetrics.h"
#include "Kyty/Agent/Runner/JsonValue.h"

#include <string>

namespace Kyty::Agent::Runner {

// External, fixture-specific image/action oracle (schema kyty_scene_checkpoint_v1).
//
// The contract names an anonymous `fixture`, a `kind` (gameplay, menu, boot,
// non_gameplay), reviewed `before` and `after` reference PNGs pinned by sha256
// (paths relative to the contract), 1..16 normalized `scene_regions`
// ({box: [x0,y0,x1,y1], max_mean_error}), a `response` region with
// pixel_delta and min_changed_ratio, and an `action` with pad_sequence,
// milestones, min_present_delta and min_settle_s. References are never
// generated by the runner. Regions compare RGB error on a bounded grid, so they
// recognize only the declared checkpoint. A changed frame alone is not enough:
// it must match the after reference and differ from the before reference in
// the response region.
class SceneCheckpoint
{
public:
	[[nodiscard]] bool Load(const std::string& contract_path, std::string* error);

	[[nodiscard]] const Json&        Contract() const { return m_contract; }
	[[nodiscard]] const std::string& Sha256() const { return m_sha256; }

	// {matches, region_errors} of a capture against the before or after reference.
	[[nodiscard]] Json Match(const std::string& path, const char* role) const;

	// Full verdict for one before/after capture pair and the delivered action.
	[[nodiscard]] Json Evaluate(const Json& before, const Json& after, const Json& action) const;

private:
	Json        m_contract;
	std::string m_sha256;
	RgbImage    m_before;
	RgbImage    m_after;
	std::string m_before_sha256;
	std::string m_after_sha256;
};

} // namespace Kyty::Agent::Runner

#endif /* KYTY_AGENT_INCLUDE_KYTY_AGENT_RUNNER_SCENECHECKPOINT_H_ */
